"use strict";
// Generates build/installer.nsh: per-user Explorer context-menu entries ("Zest" → radial wheel)
// for every supported input extension + folders, and the matching uninstall cleanup.
const fs = require("fs");
const path = require("path");
const F = require("../src/engine/formats");
const exts = [
  ...new Set([
    ...F.IMAGE_IN,
    ...F.VIDEO_IN,
    ...F.AUDIO_IN,
    ...F.PDF_IN,
    ...F.EBOOK_IN,
    ...F.DOC_IN,
    ...F.DATA_IN,
  ]),
].sort();
const key = (e) =>
  `Software\\Classes\\SystemFileAssociations\\.${e}\\shell\\Zest`;
const verb = (k) =>
  [
    `  WriteRegStr HKCU "${k}" "MUIVerb" "Zest"`,
    `  WriteRegStr HKCU "${k}" "Icon" "$INSTDIR\\Zest.exe,0"`,
    `  WriteRegStr HKCU "${k}" "MultiSelectModel" "Player"`,
    `  WriteRegStr HKCU "${k}\\command" "" '"$INSTDIR\\Zest.exe" --radial "%1"'`,
  ].join("\n");
const out = `; GENERATED by build/gen-shell-nsh.js — do not edit by hand.
; Zest Explorer integration (per user, HKCU): right-click → "Zest" opens the radial wheel.
; ${exts.length} file types + folders. Removed again by the uninstaller.

; Simple per-user "close the running app" step instead of electron-builder's GetProcessInfo/System-plugin
; check, which intermittently crashed silent installs (0xC0000005) on Windows Server 2025 runners.
!macro customCheckAppRunning
  nsExec::Exec '"$SYSDIR\\cmd.exe" /c taskkill /f /im "\${APP_EXECUTABLE_FILENAME}" /fi "USERNAME eq %USERNAME%"'
  Pop $0
  Sleep 500
!macroend

!macro customInstall
  ; clean up what the previous "Mohamed Convert" build registered (its right-click entries, startup entry and bubble shortcut)
${exts.map((e) => `  DeleteRegKey HKCU "Software\\Classes\\SystemFileAssociations\\.${e}\\shell\\MohamedConvert"`).join("\n")}
  DeleteRegKey HKCU "Software\\Classes\\Directory\\shell\\MohamedConvert"
  DeleteRegValue HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Run" "MohamedConvert"
  Delete "$SMPROGRAMS\\Mohamed Bubble.lnk"
${exts.map((e) => verb(key(e))).join("\n")}
${verb("Software\\Classes\\Directory\\shell\\Zest")}
  CreateShortCut "$SMPROGRAMS\\Zest Bubble.lnk" "$INSTDIR\\Zest.exe" "--bubble" "$INSTDIR\\Zest.exe" 0
  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'
!macroend

!macro customUnInstall
${exts.map((e) => `  DeleteRegKey HKCU "${key(e)}"`).join("\n")}
  DeleteRegKey HKCU "Software\\Classes\\Directory\\shell\\Zest"
  DeleteRegValue HKCU "Software\\Microsoft\\Windows\\CurrentVersion\\Run" "Zest"
  Delete "$SMPROGRAMS\\Zest Bubble.lnk"
  System::Call 'shell32::SHChangeNotify(i 0x08000000, i 0, p 0, p 0)'
!macroend
`;
fs.writeFileSync(path.join(__dirname, "installer.nsh"), out);
console.log(`installer.nsh: ${exts.length} extensions`);
module.exports = { exts };
